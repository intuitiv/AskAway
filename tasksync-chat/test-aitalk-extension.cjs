const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const { pathToFileURL } = require('node:url');
(async () => {
    const rules = await import(pathToFileURL(path.join(__dirname, 'media/aitalk/talkRules.js')));
    const render = await import(pathToFileURL(path.join(__dirname, 'media/aitalk/talkRender.js')));
    const mod = { exports: {} };
    vm.runInNewContext(ts.transpileModule(fs.readFileSync(path.join(__dirname, 'src/aitalk/store.ts'), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, {
        module: mod, exports: mod.exports, require: id => id.includes('talkRules') ? rules : require(id)
    });
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'aitalk-extension-'));
    const store = new mod.exports.AITalkStore(root);
    const posted = store.post('@Agent hello');
    assert.equal(posted.messages[0].author, rules.owner(posted.members).id);
    assert.deepEqual(posted.messages[0].recipients, ['agent']);
    assert.equal(new mod.exports.AITalkStore(root).snapshot().messages[0].text, '@Agent hello');
    assert.equal(new mod.exports.AITalkStore(root + '-other').snapshot().messages.length, 0);
    store.reply('quoted answer', posted.messages[0].id); store.react(posted.messages[0].id, '👍');
    assert.equal(store.snapshot().messages[1].quote.text, '@Agent hello');
    assert.equal(store.snapshot().messages[2].text, '👍');
    assert.deepEqual(store.snapshot().members.map(m => [m.id, m.rank, m.presencePolicy, m.canProxyWhenAway]), rules.defaultMembers.map(m => [m.id, m.rank, m.presencePolicy, m.canProxyWhenAway]));
    const provider = fs.readFileSync(path.join(__dirname, 'src/webview/webviewProvider.ts'), 'utf8');
    const tabs = provider.slice(provider.indexOf('<div class="widget-tabs"'), provider.indexOf('<div class="conversation-health"'));
    assert.deepEqual([...tabs.matchAll(/data-tab="([^"]+)"/g)].map(m => m[1]), ['aitalk', 'specs', 'observability', 'workers', 'settings', 'chat']);
    assert.match(provider, /type="module" nonce="\$\{nonce\}" src="\$\{talkScriptUri\}"/);
    assert.match(provider, /case 'aitalkPost'/); assert.match(provider, /store\.post\(message\.text, message\.replyTo\)/);
    assert.equal(provider.replace(/\r\n/g, '').includes('\n'), false);
    const talkProxy = fs.readFileSync(path.join(__dirname, 'storybook/prototypes/talk.js'), 'utf8');
    assert.match(talkProxy, /media\/aitalk\/talkRender/);
    assert.match(fs.readFileSync(path.join(__dirname, 'storybook/prototypes/talkRules.js'), 'utf8'), /media\/aitalk\/talkRules/);
    const host = { innerHTML: '', querySelector: () => ({ value: '@Agent composer message' }) };
    const listeners = {};
    const ui = fs.readFileSync(path.join(__dirname, 'media/aitalk/extension.js'), 'utf8').replace(/^import .*;$/gm, '').replace('export function', 'function');
    const messages = [];
    const clickHandlers = [];
    vm.runInNewContext(ui, { ...render, ...rules, window: { addEventListener: (name, fn) => { listeners[name] = fn; }, askawayPostMessage: m => messages.push(m) }, document: { getElementById: () => host, addEventListener: (name, fn) => { if (name === 'click') clickHandlers.push(fn); } } });
    listeners.message({ data: { type: 'aitalkState', data: store.snapshot() } });
    assert.ok(host.innerHTML.includes(render.threadHtml(store.snapshot().messages, store.snapshot().members)), 'real browser renders exact shared renderer output');
    assert.equal(messages[0].type, 'requestAITalk');
    clickHandlers[0]({ target: { closest: selector => selector === '#aitalk-root' ? host : { hasAttribute: name => name === 'data-send' } } });
    assert.equal(messages[1].type, 'aitalkPost');
    store.post(messages[1].text);
    listeners.message({ data: { type: 'aitalkState', data: new mod.exports.AITalkStore(root).snapshot() } });
    assert.ok(host.innerHTML.includes('composer message'), 'composer persists and rerenders after reload');
    console.log('PASS EV-AITALK-EXTENSION first tab; shared Storybook renderer/rules; workspace persistence/reload; registry; reply/react; CSP module bridge');
})().catch(error => { console.error(error); process.exitCode = 1; });
