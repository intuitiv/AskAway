const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const { pathToFileURL } = require('node:url');
(async () => {
    const rules = await import(pathToFileURL(path.join(__dirname, 'media/aitalk/talkRules.js')));
    const render = await import(pathToFileURL(path.join(__dirname, 'media/aitalk/talkRender.js')));
    const mod = { exports: {} };
    vm.runInNewContext(ts.transpileModule(fs.readFileSync(path.join(__dirname, 'src/aitalk/store.ts'), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, {
        module: mod, exports: mod.exports, require: id => id.includes('talkRules') ? rules : require(id)
    });
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'aitalk-extension-'));
    const store = new mod.exports.AITalkStore(root);
    const posted = store.post('@Agent hello');
    assert.equal(posted.messages[0].author, rules.owner(posted.members).id);
    assert.deepEqual(posted.messages[0].recipients, ['agent']);
    assert.equal(new mod.exports.AITalkStore(root).snapshot().messages[0].text, '@Agent hello');
    assert.equal(new mod.exports.AITalkStore(root + '-other').snapshot().messages.length, 0);
    store.reply('quoted answer', posted.messages[0].id); store.react(posted.messages[0].id, '👍');
    assert.equal(store.snapshot().messages[1].quote.text, '@Agent hello');
    assert.equal(store.snapshot().messages[2].text, '👍');
    assert.deepEqual(store.snapshot().members.map(m => [m.id, m.rank, m.presencePolicy, m.canProxyWhenAway]), rules.defaultMembers.map(m => [m.id, m.rank, m.presencePolicy, m.canProxyWhenAway]));
    const provider = fs.readFileSync(path.join(__dirname, 'src/webview/webviewProvider.ts'), 'utf8');
    const tabs = provider.slice(provider.indexOf('<div class="widget-tabs"'), provider.indexOf('<div class="conversation-health"'));
    // Commentary stays until agent progress lines move into AITalk (A5); Chat goes in A3.
    assert.deepEqual([...tabs.matchAll(/data-tab="([^"]+)"/g)].map(m => m[1]), ['aitalk', 'specs', 'observability', 'workers', 'settings']);
    assert.doesNotMatch(provider, /id="panel-chat"|id="chat-input"/);
    assert.ok(!require('./package.json').contributes.languageModelTools.some(tool => tool.name === 'ask_user'));
    assert.doesNotMatch(fs.readFileSync(path.join(__dirname, 'src/tools.ts'), 'utf8'), /register(?:AITalkTool|Tool)\('ask_user'/);
    assert.doesNotMatch(fs.readFileSync(path.join(__dirname, 'media/webview.js'), 'utf8'), /switchTab\('chat'\)/);
    assert.match(provider, /type="module" nonce="\$\{nonce\}" src="\$\{talkScriptUri\}"/);
    assert.match(provider, /case 'aitalkPost'/); assert.match(provider, /store\.post\(message\.text, message\.replyTo,/);
    assert.equal(provider.replace(/\r\n/g, '').includes('\n'), false);
    const talkProxy = fs.readFileSync(path.join(__dirname, 'storybook/prototypes/talk.js'), 'utf8');
    assert.match(talkProxy, /media\/aitalk\/talkRender/);
    assert.match(fs.readFileSync(path.join(__dirname, 'storybook/prototypes/talkRules.js'), 'utf8'), /media\/aitalk\/talkRules/);
    const input = { value: '@Agent composer message', selectionStart: 2, selectionEnd: 2, focus() {}, setSelectionRange() {} };
    const host = { innerHTML: '', querySelector: () => input };
    const listeners = {};
    const ui = fs.readFileSync(path.join(__dirname, 'media/aitalk/extension.js'), 'utf8').replace(/^import .*;$/gm, '').replace('export function', 'function');
    const messages = [];
    const clickHandlers = [], keyHandlers = [], compositionHandlers = {};
    vm.runInNewContext(ui, { ...render, ...rules, setInterval: () => {}, window: { addEventListener: (name, fn) => { listeners[name] = fn; }, askawayPostMessage: m => messages.push(m) }, document: { getElementById: () => host, addEventListener: (name, fn) => { if (name === 'click') clickHandlers.push(fn); if (name === 'keydown') keyHandlers.push(fn); if (name.startsWith('composition')) compositionHandlers[name] = fn; } } });
    listeners.message({ data: { type: 'aitalkState', data: store.snapshot() } });
    assert.ok(host.innerHTML.includes(render.threadHtml(store.snapshot().messages, store.snapshot().members)), 'real browser renders exact shared renderer output');
    assert.equal(messages[0].type, 'requestAITalk');
    clickHandlers[0]({ target: { closest: selector => selector === '#aitalk-root' ? host : { hasAttribute: name => name === 'data-send' } } });
    assert.equal(messages[1].type, 'aitalkPost');
    store.post(messages[1].text);
    listeners.message({ data: { type: 'aitalkState', data: new mod.exports.AITalkStore(root).snapshot() } });
    assert.ok(host.innerHTML.includes('composer message'), 'composer persists and rerenders after reload');
    assert.doesNotMatch(store.snapshot().members.map(m => m.id).join(','), /build-1/);
    mod.exports.setAITalkPresence(root, true, [{ id: 'real-worker', displayName: 'Review tests', running: true }]);
    const joined = render.headerHtml({ members: store.snapshot().members });
    assert.match(joined, /Review tests/); assert.match(joined, /You moderate<\/span>/);
    mod.exports.setAITalkPresence(root, false, [{ id: 'real-worker', displayName: 'Review tests', running: false }]);
    const left = render.headerHtml({ members: store.snapshot().members }); assert.doesNotMatch(left, /Review tests|>Agent</);
    assert.match(render.headerHtml({ members: [{ id: 'v', displayName: 'Validator', rank: 300, presence: 'online' }] }), /Validator moderates/);
    const css = fs.readFileSync(path.join(__dirname, 'media/aitalk/talk.css'), 'utf8'); assert.match(css, /caret-color: var\(--vscode-input-foreground\)/);
    const files = [{ name: 'notes.txt', path: '/synthetic/notes.txt' }];
    store.post('@Agent files to review', undefined, undefined, undefined, undefined, files);
    assert.deepEqual(Array.from(store.takeForTool('agent').at(-1).attachments, f => ({ ...f })), files);
    assert.match(render.composerHtml({ emoji: true, attachments: files }), /data-insert-emoji="👍"/);
    assert.match(provider, /showOpenDialog/); assert.match(provider, /aitalkAttachments/);
    console.log('PASS live presence and rank moderator; theme composer; emoji picker and attachment storage/delivery');
    const target = { matches: () => true, closest: () => undefined };
    const beforeKeys = messages.length;
    keyHandlers[0]({ target, key: 'Enter', shiftKey: true });
    keyHandlers[0]({ target, key: 'Enter', isComposing: true });
    assert.equal(messages.length, beforeKeys);
    let prevented = false;
    keyHandlers[0]({ target, key: 'Enter', preventDefault: () => { prevented = true; } });
    assert.equal(prevented, true); assert.equal(messages.at(-1).type, 'aitalkPost');
    const click = button => clickHandlers[0]({ target: { closest: selector => selector === '#aitalk-root' ? host : button } });
    click({ hasAttribute: name => name === 'data-emoji', dataset: {} });
    assert.match(host.innerHTML, /talk-emoji-picker/);
    click({ hasAttribute: () => false, dataset: { insertEmoji: '👍' } });
    assert.match(host.innerHTML, /@A👍gent composer message/);
    click({ hasAttribute: name => name === 'data-attach', dataset: {} });
    assert.equal(messages.at(-1).type, 'aitalkAttach');
    listeners.message({ data: { type: 'aitalkAttachments', files } });
    assert.match(host.innerHTML, /notes.txt/);
    console.log('PASS Enter sends; Shift+Enter and IME do not; emoji inserts at caret; attachment picker request and name chip');
    mod.exports.setAITalkPresence(root, true, [{ id: 'worker-a', displayName: 'build', running: true }, { id: 'worker-b', displayName: 'build', running: true }]);
    store.post('@worker-a only this worker');
    const peers = store.snapshot().members.filter(m => m.kind === 'worker');
    assert.equal(new Set(peers.map(m => m.displayName)).size, 2);
    assert.deepEqual(Array.from(store.snapshot().messages.at(-1).recipients), ['worker-a']);
    mod.exports.setAITalkPresence(root, false, [{ id: 'worker-a', displayName: 'build', running: false }, { id: 'worker-b', displayName: 'build', running: true }]);
    assert.equal(store.snapshot().members.find(m => m.id === 'worker-a').presence, 'left');
    assert.doesNotMatch(render.headerHtml({ members: store.snapshot().members }), /build · worker-a/);
    const composingTarget = { matches: () => true, value: 'composing text' };
    compositionHandlers.compositionstart({ target: composingTarget });
    const unchanged = host.innerHTML;
    listeners.message({ data: { type: 'aitalkState', data: { members: store.snapshot().members, messages: [{ id: 'ime-new', author: 'agent', text: 'new during composition' }] } } });
    assert.equal(host.innerHTML, unchanged);
    compositionHandlers.compositionend({ target: composingTarget });
    assert.match(host.innerHTML, /new during composition/);
    assert.doesNotMatch(fs.readFileSync(path.join(__dirname, 'media/aitalk/talkRender.js'), 'utf8'), /build-1|export const (?:scenarios|liveScript|liveStart|traceSessions|fullConversation)/);
    console.log('PASS authoritative worker presence after replay; stable-id worker routing; IME refresh deferred; production demo-free');
    console.log('PASS EV-AITALK-EXTENSION first tab; shared Storybook renderer/rules; workspace persistence/reload; registry; reply/react; CSP module bridge');
})().catch(error => { console.error(error); process.exitCode = 1; });
