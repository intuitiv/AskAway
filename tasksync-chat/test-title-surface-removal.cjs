const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const manifest = require('./package.json');
const read = name => fs.readFileSync(path.join(__dirname, name), 'utf8');
const removed = /askaway\.(?:.*Remote|openHistory|newSession|openSettings)/;
// Bug 6 (2026-10-12): the AITalk avatar menu replaced the view-title availability icons.
assert.ok(!(manifest.contributes.menus?.['view/title'] || []).some(row => /^askaway\.availability\./.test(row.command)));
assert.ok(manifest.contributes.commands.every(row => !removed.test(row.command)));
assert.ok(Object.keys(manifest.contributes.configuration.properties).every(key => !/^askaway\.remote/.test(key)));
assert.ok(!manifest.contributes.languageModelTools.some(tool => tool.name === 'ask_user'));
const extension = read('src/extension.ts');
assert.doesNotMatch(extension, /remoteUiServer|remoteServerRunning|remoteEnabled|remotePort/);
const provider = read('src/webview/webviewProvider.ts');
assert.doesNotMatch(provider, /_remoteBroadcastCallback|_currentPendingRequest|setRemoteBroadcastCallback|getStateForRemote|handleRemoteMessage/);
assert.equal(provider.replace(/\r\n/g, '').includes('\n'), false, 'provider remains CRLF');
for (const tab of ['aitalk', 'settings']) assert.match(provider, new RegExp('data-tab="' + tab + '"'));
assert.doesNotMatch(provider, /data-tab="chat"|id="panel-chat"/);
assert.ok(provider.includes("case 'openSettingsModal'"), 'shared webview handler remains: openSettingsModal');
// Chat tab removal (2026-10-13): its input, queue editing and history modal handlers are gone from both sides.
for (const message of ['openHistoryModal', 'submit', 'addQueuePrompt', 'removeHistoryItem', 'clearPersistedHistory']) assert.ok(!provider.includes("case '" + message + "'"), 'Chat handler removed: ' + message);
assert.doesNotMatch(read('media/webview.js'), /function (handleSend|renderCurrentSession|renderHistoryModal|renderQueue|selectCard)\(/);
assert.doesNotMatch(read('media/main.css'), /\.(history-modal|tool-call-card|queue-item|approval-bar|welcome-section)\b/);
assert.ok(provider.includes('public startNewSession()'), 'shared session logic remains');
const ast = ts.createSourceFile('provider.ts', provider, ts.ScriptTarget.Latest, true);
const klass = ast.statements.find(node => ts.isClassDeclaration(node) && node.name.text === 'TaskSyncWebviewProvider');
const broadcast = klass.members.find(node => node.name?.getText(ast) === '_broadcast');
const code = ts.transpileModule('class Provider {' + broadcast.getText(ast) + '} out.Provider = Provider;', { compilerOptions: { target: ts.ScriptTarget.ES2020 } }).outputText;
const out = {};
vm.runInNewContext(code, { out });
const instance = new out.Provider();
const received = [];
instance._view = { webview: { postMessage: message => received.push(message) } };
const message = { type: 'toolCallPending', id: 'caller-question' };
instance._broadcast(message);
assert.deepEqual(received, [message], 'local caller still receives updates');
instance._view = undefined;
assert.doesNotThrow(() => instance._broadcast(message));
assert.doesNotMatch(read('media/webview.js'), /dispatchVSCodeMessage/);
assert.doesNotMatch(read('README.md'), /Remote Mobile & Web Access|REMOTE_ACCESS\.md/);
console.log('PASS title surface removal: availability, AITalk, Settings and local delivery preserved; Chat and ask_user LM removed');
