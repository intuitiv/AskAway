const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const esbuild = require('esbuild');
(async () => {
    const build = await esbuild.build({ stdin: { contents: "export * from './src/aitalk/store'; export * from './src/aitalk/delivery'; export * from './src/aitalk/actors'; export * from './src/workers/workerTools'; export * from './src/commentary/commentary';", resolveDir: __dirname }, bundle: true, platform: 'node', format: 'cjs', write: false });
    const mod = { exports: {} }; new Function('require', 'module', 'exports', build.outputFiles[0].text)(require, mod, mod.exports);
    const { AITalkStore, configureAITalkDelivery, appendAITalkDelivery, setToolResultDelivery, invokeDefinition, commentaryToolDefinitions, registerToolDefinitions, withAITalkMcpDelivery, roomFor } = mod.exports;
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'aitalk-delivery-'));
    const store = new AITalkStore(root); const members = store.snapshot().members;
    const agent = members.find(m => m.kind === 'agent'), validator = members.find(m => m.kind === 'validator');
    // Agent registers at turn start, Validator at activation; only registered actors post.
    roomFor(root).registerAgent(); roomFor(root).register({ id: validator.id, displayName: validator.displayName, kind: 'validator', rank: validator.rank });
    store.post('unaddressed'); store.post(`@${agent.displayName} use green`);
    const question = store.post('which colour?', undefined, agent.id, 'for example green').messages.at(-1);
    store.post('blue instead', question.id); store.post(`@${agent.id} confirmed`, undefined, validator.id);
    configureAITalkDelivery(root); setToolResultDelivery(appendAITalkDelivery);
    const { z } = require('zod'); const tool = { name: 'any-tool', inputSchema: z.object({}), run: () => ({ status: 'ok' }) };
    assert.equal(store.snapshot().messages.find(m => m.text === 'blue instead').delivery, 'posted');
    const result = await invokeDefinition(tool, {});
    assert.match(result, /use green/); assert.match(result, /blue instead/); assert.match(result, /confirmed/); assert.doesNotMatch(result, /unaddressed/);
    assert.equal(store.snapshot().messages.find(m => m.text === 'blue instead').delivery, 'delivered');
    const [commentary] = commentaryToolDefinitions(() => { throw Error('not commentary'); }, root);
    const response = await invokeDefinition(commentary, { action: 'aitalk', text: 'got it', details: 'longer explanation' });
    assert.doesNotMatch(response, /AITalk addressed messages/);
    assert.equal(new AITalkStore(root).snapshot().messages.find(m => m.text === 'blue instead').delivery, 'read');
    assert.equal(store.snapshot().messages.at(-1).details, 'longer explanation');
    const next = await invokeDefinition(tool, {}); assert.doesNotMatch(next, /AITalk addressed messages/);
    store.post(`@${agent.id} next`); await invokeDefinition(tool, {});
    assert.equal(store.snapshot().messages.at(-1).delivery, 'delivered'); await invokeDefinition(tool, {});
    assert.equal(store.snapshot().messages.at(-1).delivery, 'read');
    store.post(`@${agent.id} retained`);
    for (let i = 0; i < 600; i++) store.post(`newer ${i}`);
    assert.equal(store.snapshot().messages.length, 500);
    assert.match(await invokeDefinition(tool, {}), /retained/);
    console.log('PASS pending addressed message survives 600 newer visible messages');
    roomFor(root).workerLifecycle({ id: 'test-worker', displayName: 'Test worker' }, true);
    assert.equal(store.snapshot().members.some(m => m.kind === 'worker'), false, 'a running worker is not registered until it posts');
    roomFor(root).workerPost('test-worker', 'Need a hand?');
    const worker = store.snapshot().members.find(m => m.kind === 'worker');
    store.post(`@${worker.id} worker task`, undefined, agent.id);
    let mcpCall; registerToolDefinitions((name, config, handler) => { mcpCall = handler; }, [tool]);
    const extra = { _meta: { recipient: worker.id, workspacePath: root } };
    const workerResult = await mcpCall({}, extra);
    assert.match(workerResult.content[0].text, /worker task/);
    assert.equal(store.snapshot().messages.at(-1).delivery, 'delivered');
    assert.doesNotMatch(appendAITalkDelivery('another completion', { recipient: worker.id, workspace: root }), /worker task/);
    assert.equal(store.snapshot().messages.at(-1).delivery, 'delivered', 'completion alone is not a recipient-originated event');
    assert.doesNotMatch((await mcpCall({}, extra)).content[0].text, /worker task/);
    assert.equal(store.snapshot().messages.at(-1).delivery, 'read');
    console.log('PASS MCP caller identity routes worker messages once; completion does not mark read; recipient next call does');
    store.post(`@${worker.id} direct MCP`, undefined, agent.id);
    const directMcp = withAITalkMcpDelivery(async () => ({ content: [{ type: 'text', text: 'normal result' }] }), root);
    const direct = await directMcp({}, { _meta: { workerId: worker.id } });
    assert.equal(direct.content[0].text, 'normal result'); assert.match(direct.content[1].text, /direct MCP/);
    assert.equal((await directMcp({}, { _meta: { workerId: worker.id } })).content.length, 1);
    assert.equal(store.snapshot().messages.at(-1).delivery, 'read');
    console.log('PASS server MCP boundary also covers direct tools with workerId metadata');
    const futureRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'aitalk-future-'));
    const future = new AITalkStore(futureRoot, [...members, worker, { id: 'custom', displayName: 'Custom', kind: 'future', rank: 250 }]);
    future.setPresence(worker, true); future.post('@custom routed', undefined, worker.id);
    assert.equal(future.takeForTool('custom')[0].text, '@custom routed');
    console.log('PASS future participant kinds use generic routing without author-kind allowlist');
    const vm = require('node:vm'); const { pathToFileURL } = require('node:url');
    const rules = await import(pathToFileURL(path.join(__dirname, 'media/aitalk/talkRules.js')));
    const render = await import(pathToFileURL(path.join(__dirname, 'media/aitalk/talkRender.js')));
    const { createTalkController } = await import('./media/aitalk/talkController.js');
    let textarea = { value: 'draft text', selectionStart: 2, selectionEnd: 5, selectionDirection: 'forward', focus() { document.activeElement = this; }, setSelectionRange(...args) { this.range = args; } };
    const document = { activeElement: textarea, getElementById: () => host, addEventListener: () => {} };
    let html = ''; const host = { querySelector: () => textarea, set innerHTML(value) { html = value; textarea = { ...textarea, value: 'draft text' }; }, get innerHTML() { return html; } };
    const context = { ...render, ...rules, createTalkController, document, window: { addEventListener: () => {}, askawayPostMessage: () => {} }, setInterval: () => {} };
    vm.createContext(context);
    vm.runInContext(fs.readFileSync(path.join(__dirname, 'media/aitalk/extension.js'), 'utf8').replace(/^import .*;$/gm, '').replace('export function', 'function'), context);
    context.initial = { members, messages: [{ id: 'expanded', text: 'short', details: 'expanded details', expanded: true }] };
    vm.runInContext('renderAITalk(initial);', context);
    document.activeElement = textarea;
    context.refresh = { members, messages: [{ id: 'expanded', text: 'short', details: 'expanded details' }] };
    vm.runInContext('renderAITalk(refresh);', context);
    assert.equal(textarea.value, 'draft text'); assert.equal(document.activeElement, textarea); assert.deepEqual(Array.from(textarea.range), [2, 5, 'forward']);
    assert.ok(html.includes('expanded details')); assert.ok(!html.includes('data-more="expanded">Read more'));
    console.log('PASS polling refresh preserves composer text, focus, selection and expanded details');
    const tools = fs.readFileSync(path.join(__dirname, 'src/tools.ts'), 'utf8'); assert.match(tools, /setToolResultDelivery\(appendAITalkDelivery\)/); assert.match(tools, /registerAITalkTool\('read_doc'/);
    const provider = fs.readFileSync(path.join(__dirname, 'src/webview/webviewProvider.ts'), 'utf8'); assert.equal(provider.replace(/\r\n/g, '').includes('\n'), false);
    console.log('PASS EV-AITALK-DELIVERY mention/reply/Validator handoff once; posted → delivered → read; next tool or post; unaddressed excluded; crisp/details; LM boundary wired');
})().catch(error => { console.error(error); process.exitCode = 1; });
