const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const cp = require('node:child_process');
const vm = require('node:vm');
const os = require('node:os');
async function main() {
    const root = path.join(__dirname, 'test-fixtures/style');
    const script = path.join(__dirname, 'tools/style-sample-vscode.cjs');
    const temp = await fs.mkdtemp(path.join(os.tmpdir(), 'style-sample-'));
    const out = path.join(temp, 'output.json');
    const trackedOutput = await fs.readFile(path.join(root, 'output.json'), 'utf8');
    const copilotRoot = path.join(root, 'session-state');
    const run = (...args) => { const result = cp.spawnSync(process.execPath, [script, '--copilot-root', copilotRoot, ...args], { encoding: 'utf8' }); assert.equal(result.status, 0, result.stderr); return result; };
    run('--root', path.join(root, 'storage'), '--out', out);
    const sample = JSON.parse(await fs.readFile(out, 'utf8'));
    assert.equal(sample.source, 'vscode'); assert.ok(Number.isFinite(Date.parse(sample.collectedAt)));
    assert.deepEqual(sample.messages, [{ ts: 800, text: 'why this PR failed?' }, { ts: 600, text: 'i want teh simple wording' }, { ts: 500, text: 'please keep this session prose' }, { ts: 450, text: 'please keep CLI original spelling' }, { ts: 200, text: 'keep my original spelling here' }]);
    assert.doesNotMatch(JSON.stringify(sample), /transformed|injected|assistant CLI|tool CLI/);
    console.log('PASS Copilot CLI data.content only; transformedContent excluded; shared cleaning and cross-source newest-first dedupe');
    console.log('PASS typed main-log and session messages only; spelling preserved; code/paths/logs/attachments/short/slash-only dropped; newest duplicate retained');
    const bulk = path.join(temp, 'bulk/workspace/GitHub.copilot-chat/debug-logs/session');
    await fs.mkdir(bulk, { recursive: true });
    await fs.writeFile(path.join(bulk, 'main.jsonl'), Array.from({ length: 230 }, (_, i) => JSON.stringify({ type: 'user_message', ts: 1000 + i, attrs: { text: `please keep synthetic message number ${i}` } })).join('\n'));
    run('--root', path.join(root, 'storage'), '--root', path.join(temp, 'bulk'), '--root', path.join(temp, 'bulk'), '--out', out, '--max', '999');
    const capped = JSON.parse(await fs.readFile(out, 'utf8')).messages;
    assert.equal(capped.length, 200); assert.equal(capped[0].ts, 1229); assert.equal(capped.at(-1).ts, 1030);
    assert.equal(new Set(capped.map(row => row.text)).size, 200);
    run('--root', path.join(temp, 'bulk'), '--out', out, '--max', '7');
    assert.equal(JSON.parse(await fs.readFile(out, 'utf8')).messages.length, 7);
    console.log('PASS repeated roots deduped; newest-first cap 200; smaller --max honored');
    const allowed = new Set(['node:fs/promises', 'node:path', 'node:os', 'node:readline', 'node:fs']);
    const mod = { exports: {} };
    vm.runInNewContext(await fs.readFile(script, 'utf8'), { module: mod, require: name => { assert.ok(allowed.has(name), `no dependencies/network/model: ${name}`); return require(name); }, console, fetch: () => { throw Error('network forbidden'); } });
    await mod.exports.main(['--root', path.join(root, 'storage'), '--copilot-root', copilotRoot, '--out', out]);
    assert.equal(JSON.parse(await fs.readFile(out, 'utf8')).messages.length, 5);
    const home = path.join(temp, 'synthetic-home');
    await fs.cp(copilotRoot, path.join(home, '.copilot/session-state'), { recursive: true });
    const defaults = { exports: {} };
    vm.runInNewContext(await fs.readFile(script, 'utf8'), { module: defaults, require: name => {
        assert.ok(allowed.has(name));
        return name === 'node:os' ? { homedir: () => home } : require(name);
    }, console });
    await defaults.exports.main(['--root', path.join(root, 'storage'), '--out', out]);
    assert.deepEqual(JSON.parse(await fs.readFile(out, 'utf8')).messages, sample.messages);
    console.log('PASS default extra root uses synthetic ~/.copilot/session-state; no real user sessions read');
    assert.equal(await fs.readFile(path.join(root, 'output.json'), 'utf8'), trackedOutput);
    console.log('PASS output and generated bulk fixtures stay in os.tmpdir(); tracked fixture output unchanged');
    console.log('PASS zero network/model calls; built-in modules only');
    console.log('PASS EV-STYLE-SAMPLE-VSCODE');
}
main().catch(error => { console.error(error); process.exitCode = 1; });
