const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const cp = require('node:child_process');
const ts = require('typescript');
const build = path.join(__dirname, 'build');
fs.mkdirSync(build, { recursive: true });
const home = fs.mkdtempSync(path.join(build, 'progress-home-'));
const workspace = path.join(home, 'workspace');
fs.mkdirSync(workspace);
const exportsBox = {};
new Function('exports', ts.transpileModule(fs.readFileSync(path.join(__dirname, 'src/hooks/subagentTimerScript.ts'), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText)(exportsBox);
const script = path.join(home, 'timer.cjs');
fs.writeFileSync(script, exportsBox.SUBAGENT_TIMER_INJECT_SCRIPT);
const fire = (event, time, sid = 'main', toolUseId = String(time)) => cp.execFileSync(process.execPath, ['-e', `Date.now=()=>${time};require(${JSON.stringify(script)})`], { env: { ...process.env, HOME: home }, input: JSON.stringify({ hook_event_name: event, session_id: sid, cwd: workspace, tool_name: 'read_file', tool_use_id: toolUseId }), encoding: 'utf8' });
assert.equal(fire('PostToolUse', 500000), '', 'no running turn');
fire('UserPromptSubmit', 1000);
assert.equal(fire('PostToolUse', 120999), '', 'before inclusive two-minute boundary');
assert.match(fire('PostToolUse', 121000), /Status update due.*call the aitalk tool \(action say\)/);
assert.equal(fire('PreToolUse', 121001, 'main', '121000'), '', 'pre hook never emits main reminder');
assert.equal(fire('PostToolUse', 121002, 'main', '121000'), '', 'duplicate result delivery emits no second reminder');
assert.match(fire('PostToolUse', 121003, 'main', 'next-result'), /Status update due/, 'an unanswered reminder repeats on a distinct result');
assert.match(fire('PostToolUse', 241003, 'main', 'next-result-2'), /Status update due/, 'and keeps repeating');
assert.equal(fire('PostToolUse', 241000, 'other'), '', 'other session excluded');
const hostBox = {};
const commentaryBox = {};
new Function('require', 'exports', ts.transpileModule(fs.readFileSync(path.join(__dirname, 'src/commentary/commentary.ts'), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText)(id => id === 'os' ? { homedir: () => home } : require(id), commentaryBox);
new Function('require', 'exports', ts.transpileModule(fs.readFileSync(path.join(__dirname, 'src/workers/workerHost.ts'), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText)(id => id === 'os' ? { homedir: () => home } : id === '../commentary/commentary' ? commentaryBox : id.startsWith('.') ? {} : require(id), hostBox);
const actualNow = Date.now;
Date.now = () => 241000;
const store = hostBox.sharedCommentaryStore();
const tool = commentaryBox.commentaryToolDefinitions(() => store, workspace)[0];
assert.equal(tool.run({ kind: 'update', text: 'Checking the current changes before running the tests.' }).status, 'POSTED');
Date.now = actualNow;
assert.equal(fire('PostToolUse', 360999), '', 'a post resets the clock');
assert.match(fire('PostToolUse', 361000), /Status update due/);
fire('Stop', 481001);
assert.equal(fire('PostToolUse', 900000), '', 'stopped turn silent');
console.log('PASS main progress hook: once per tool result; two-minute boundary; commentary reset; stopped and unrelated sessions silent');
